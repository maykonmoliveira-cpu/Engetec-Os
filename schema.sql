create table if not exists public.ordens_servico (
 id bigint generated by default as identity primary key,
 user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
 numero text not null,
 data date not null,
 hora time,
 status text not null default 'Aberta' check(status in ('Aberta','Em andamento','Concluída')),
 cliente text not null, documento text, contato text, endereco text,
 equipamento text not null, marca text, modelo text, serie text, patrimonio text,
 relato text, diagnostico text, servico text, pecas text, tecnico text not null,
 assinatura_cliente text, assinatura_tecnico text,
 created_at timestamptz not null default now()
);
create unique index if not exists ordens_servico_user_numero_uidx on public.ordens_servico(user_id,numero);
alter table public.ordens_servico enable row level security;
create policy "select own os" on public.ordens_servico for select to authenticated using(auth.uid()=user_id);
create policy "insert own os" on public.ordens_servico for insert to authenticated with check(auth.uid()=user_id);
create policy "update own os" on public.ordens_servico for update to authenticated using(auth.uid()=user_id) with check(auth.uid()=user_id);
create policy "delete own os" on public.ordens_servico for delete to authenticated using(auth.uid()=user_id);
